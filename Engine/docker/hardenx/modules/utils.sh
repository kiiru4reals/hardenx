#!/usr/bin/env bash

# ----------------------------------------------------------------------------
# Log Function
# ----------------------------------------------------------------------------
log() {
    local msg="$*"
    local log_file="${LOG_FILE:-$HOME/hardenx.log}"

    mkdir -p "$(dirname "$log_file")"
    echo "$(date '+%F %T') $msg" | tee -a "$log_file"
}

# ----------------------------------------------------------------------------
# Section Header
# ----------------------------------------------------------------------------
section() {
    local title="$1"

    echo
    echo "=============================================================="
    echo " $title"
    echo "=============================================================="
}

# ----------------------------------------------------------------------------
# Check if a command exists
# ----------------------------------------------------------------------------
require_command() {
    local cmd="$1"

    if ! command -v "$cmd" >/dev/null 2>&1; then
        echo "[!] Required command not found: $cmd"
        return 1
    fi
}

# ----------------------------------------------------------------------------
# Safe Directory Creation
# ----------------------------------------------------------------------------
ensure_dir() {
    local dir="$1"
    mkdir -p "$dir"
}


# ----------------------------------------------------------------------------
# Standard Logging
# ----------------------------------------------------------------------------
log() {
    # Suppress normal output in quiet mode unless verbose is enabled
    if [[ "${QUIET:-false}" == true && "${VERBOSE:-false}" != true ]]; then
        return
    fi

    echo "$(date +'%Y-%m-%d %H:%M:%S') $*"
}

# ----------------------------------------------------------------------------
# Debug Logging
# ----------------------------------------------------------------------------
debug() {
    if [[ "${VERBOSE:-false}" == true ]]; then
        echo "[DEBUG] $*"
    fi
}